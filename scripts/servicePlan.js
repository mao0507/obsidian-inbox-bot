import path from "node:path";

// 依作業系統產生「要做哪些事」的步驟清單，本身不做任何 I/O（實際執行在 service.js），所以可以直接測三個平台。
//
// 開機啟動的做法：三個平台都用「使用者登入時跑一次 pm2 resurrect」，把 pm2 save 存下來的程序叫回來，
// 都不需要系統管理員權限：
//   - Windows：在「啟動」資料夾放一支 .vbs，用隱藏視窗執行（工作排程器的登入觸發需要系統管理員權限）
//   - macOS：~/Library/LaunchAgents 的 plist（RunAtLoad）
//   - Linux：systemd user unit（登入後啟動）
// launchd / systemd 啟動的程序 PATH 很精簡，找不到 claude、notebooklm、yt-dlp 這些 CLI，所以把安裝當下的 PATH 帶進去。
//
// Step 形狀：
//   { type: "check",  command, hint }       檢查外部 CLI 是否存在，沒有就印出 hint（不自動安裝）
//   { type: "run",    cmd, args }           執行指令（stdio 直接接到終端機）
//   { type: "write",  path, content }       寫檔（會建立上層資料夾）
//   { type: "remove", path }                刪檔（不存在就略過）

export const APP_NAME = "obsidian-inbox-bot";

const INSTALL_HINTS = {
  git: { win32: "winget install Git.Git", darwin: "xcode-select --install", linux: "sudo apt install git" },
  "yt-dlp": { win32: "winget install yt-dlp.yt-dlp", darwin: "brew install yt-dlp", linux: "pipx install yt-dlp" },
  notebooklm: 'uv tool install "notebooklm-py[browser]" 然後 notebooklm login', // 三個平台相同
};

function installHint(command, platform) {
  const hint = INSTALL_HINTS[command];
  return typeof hint === "string" ? hint : hint[platform] || hint.linux;
}

const PURPOSE = {
  git: "vault 自動同步到 git",
  "yt-dlp": "YouTube 影片字幕",
  notebooklm: "/notebook 研究",
};

function startupEntry({ platform, home, appData, nodePath, pm2Path, envPath }) {
  if (platform === "win32") {
    const q = (s) => `""${s}""`; // VBScript 字串裡的雙引號要寫成兩個
    return {
      path: path.win32.join(appData, "Microsoft", "Windows", "Start Menu", "Programs", "Startup", `${APP_NAME}.vbs`),
      content: [
        `' ${APP_NAME}: run "pm2 resurrect" hidden at login (generated by pnpm run service:install)`, // WSH 用 ANSI 讀檔，維持純 ASCII
        'Set shell = CreateObject("WScript.Shell")',
        `shell.Run "${q(nodePath)} ${q(pm2Path)} resurrect", 0, False`,
        "",
      ].join("\r\n"),
    };
  }

  if (platform === "darwin") {
    return {
      path: path.posix.join(home, "Library", "LaunchAgents", `com.${APP_NAME}.plist`),
      content: `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>com.${APP_NAME}</string>
  <key>ProgramArguments</key>
  <array>
    <string>${nodePath}</string>
    <string>${pm2Path}</string>
    <string>resurrect</string>
  </array>
  <key>EnvironmentVariables</key>
  <dict><key>PATH</key><string>${envPath}</string></dict>
  <key>RunAtLoad</key><true/>
</dict>
</plist>
`,
    };
  }

  // linux：寫法比照 pm2 官方的 systemd 範本（pm2 resurrect 會 fork 出 daemon 後結束，所以用 forking）
  return {
    path: path.posix.join(home, ".config", "systemd", "user", `${APP_NAME}.service`),
    content: `[Unit]
Description=${APP_NAME} (pm2)

[Service]
Type=forking
Environment=PATH=${envPath}
Environment=PM2_HOME=${home}/.pm2
PIDFile=${home}/.pm2/pm2.pid
ExecStart=${nodePath} ${pm2Path} resurrect
ExecReload=${nodePath} ${pm2Path} reload all
ExecStop=${nodePath} ${pm2Path} kill

[Install]
WantedBy=default.target
`,
  };
}

/**
 * @param {"install"|"uninstall"|"logs"|"restart"} action
 * @param {{ platform: string, home: string, appData?: string, nodePath: string, pm2Path: string, repoDir: string, envPath: string }} env
 */
export function planService(action, env) {
  const pm2 = (...args) => ({ type: "run", cmd: env.nodePath, args: [env.pm2Path, ...args] });
  const entry = startupEntry(env);
  const systemctl = (...args) => ({ type: "run", cmd: "systemctl", args: ["--user", ...args] });
  const unitName = `${APP_NAME}.service`;

  switch (action) {
    case "install":
      return [
        ...Object.keys(INSTALL_HINTS).map((command) => ({
          type: "check",
          command,
          hint: `${PURPOSE[command]}需要「${command}」，安裝：${installHint(command, env.platform)}`,
        })),
        pm2("start", "ecosystem.config.cjs"),
        pm2("save"),
        { type: "write", ...entry },
        ...(env.platform === "linux" ? [systemctl("daemon-reload"), systemctl("enable", unitName)] : []),
      ];
    case "uninstall":
      return [
        pm2("delete", APP_NAME),
        pm2("save", "--force"),
        ...(env.platform === "linux" ? [systemctl("disable", unitName)] : []),
        { type: "remove", path: entry.path },
      ];
    case "logs":
      return [pm2("logs", APP_NAME)];
    case "restart":
      return [pm2("restart", APP_NAME)];
    default:
      throw new Error(`未知的動作「${action}」，可用：install / uninstall / logs / restart`);
  }
}
